#pragma once

#include <string>

namespace BlackRabbitMQ {

// Параметры защищённого соединения (amqps).
//
// Умолчания строгие: без явного отказа компонента не станет разговаривать
// с брокером, чей сертификат не проверяется. Это важнее удобства — компонента
// работает внутри процесса 1С и носит учётные данные пользователя, а молчаливое
// доверие любому сертификату превращает TLS в видимость защиты.
struct TlsOptions {
    // Проверять цепочку сертификата брокера.
    bool verifyPeer = true;
    // Сверять имя хоста с CN/SAN сертификата. Без этого валидный сертификат
    // чужого сервера тоже подойдёт.
    bool verifyHostname = true;
    // PEM с доверенным корнем (файл или каталог). Пусто — системное хранилище.
    // Для самоподписанных брокеров указывать обязательно.
    std::string caFile;
};

} // namespace BlackRabbitMQ
